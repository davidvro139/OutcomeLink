/**
 * Combines a specific requested `programId` (already validated as accessible
 * by the caller) with a scoped user's whole accessible set when none was
 * requested — never both at once, since `programId` can't appear twice in
 * the same `where`/nested filter object.
 */
function programScopeCondition(
  programId: number | undefined,
  accessibleProgramIds: number[] | null,
): { programId?: number | { in: number[] } } {
  if (programId !== undefined) return { programId };
  if (accessibleProgramIds) return { programId: { in: accessibleProgramIds } };
  return {};
}

async function findOwnedPeriod(institutionId: number, reportingPeriodId: number) {
  const period = await prisma.reportingPeriod.findFirst({
    where: { id: reportingPeriodId, institutionId },
  });
  if (!period) throw ApiError.notFound("Reporting period not found");
  return period;
}

export async function compute(req: Request, res: Response) {
  const reportingPeriodId = Number(req.params.id);
  await findOwnedPeriod(req.user!.institutionId, reportingPeriodId);
  await assertPeriodIsEditable(reportingPeriodId);
  await computeReportingPeriod(reportingPeriodId);
  sendData(res, { computed: true });
}

export const listResultsQuerySchema = z.object({
  programId: z.coerce.number().int().positive().optional(),
});

export async function listResults(req: Request, res: Response) {
  const reportingPeriodId = Number(req.params.id);
  await findOwnedPeriod(req.user!.institutionId, reportingPeriodId);
  const { programId } = req.query as unknown as z.infer<typeof listResultsQuerySchema>;
  const accessibleProgramIds = await getAccessibleProgramIds(req.user!);
  assertProgramAccessible(programId, accessibleProgramIds);

  const results = await prisma.cplCalculationResult.findMany({
    where: { reportingPeriodId, ...programScopeCondition(programId, accessibleProgramIds) },
    include: { program: { select: { id: true, name: true } } },
    orderBy: [{ programId: "asc" }, { metric: "asc" }],
  });
  sendData(res, { results });
}

/** Phase 2 P7 (docs/TODO.md): the CPL Dashboard's numbers as a downloadable .xlsx. */
export async function exportResults(req: Request, res: Response) {
  const reportingPeriodId = Number(req.params.id);
  const period = await findOwnedPeriod(req.user!.institutionId, reportingPeriodId);
  const accessibleProgramIds = await getAccessibleProgramIds(req.user!);

  const results = await prisma.cplCalculationResult.findMany({
    where: { reportingPeriodId, ...programScopeCondition(undefined, accessibleProgramIds) },
    include: { program: { select: { id: true, name: true } } },
    orderBy: [{ programId: "asc" }, { metric: "asc" }],
  });

  await sendXlsx(res, `cpl-results-${period.label}.xlsx`, [
    buildProvenanceSheet([
      ["Report"],
      ["Name", "CPL Results"],
      ["Generated at", formatTimestamp(new Date())],
      ["Generated by", await describeGeneratedBy(req.user!.sub)],
      ["Rows", String(results.length)],
      ["Reporting periods"],
      ...(await describePeriods([period])),
    ]),
    {
      name: "CPL Results",
      columns: [
        { header: "Program", key: "program", width: 32 },
        { header: "Metric", key: "metric", width: 14 },
        { header: "Numerator", key: "numerator", width: 12 },
        { header: "Denominator", key: "denominator", width: 12 },
        { header: "Percentage", key: "percentage", width: 12 },
      ],
      rows: results.map((r) => ({
        program: r.program?.name ?? "Institution-wide",
        metric: r.metric,
        numerator: r.numerator,
        denominator: r.denominator,
        percentage: Number(r.percentage),
      })),
    },
  ]);
}

export const drillDownQuerySchema = z.object({
  metric: z.enum(CPL_METRICS),
  programId: z.coerce.number().int().positive().optional(),
  bucket: z.enum(["numerator", "denominator", "excluded"]),
});
type DrillDownQuery = z.infer<typeof drillDownQuerySchema>;

/** Spec §20: every metric must be drillable down to the students behind it and why. */
export async function drillDown(req: Request, res: Response) {
  const reportingPeriodId = Number(req.params.id);
  await findOwnedPeriod(req.user!.institutionId, reportingPeriodId);
  const { metric, programId, bucket } = req.query as unknown as DrillDownQuery;
  const accessibleProgramIds = await getAccessibleProgramIds(req.user!);
  assertProgramAccessible(programId, accessibleProgramIds);

  const bucketFilter =
    bucket === "numerator"
      ? { countsInNumerator: true }
      : bucket === "denominator"
        ? { countsInDenominator: true }
        : { countsInNumerator: false, countsInDenominator: false };

  const classifications = await prisma.studentClassification.findMany({
    where: {
      reportingPeriodId,
      metric,
      explanation: bucketFilter,
      studentEnrollment: programScopeCondition(programId, accessibleProgramIds),
    },
    include: {
      explanation: true,
      studentEnrollment: {
        include: {
          student: { select: { id: true, firstName: true, lastName: true } },
          program: { select: { id: true, name: true } },
        },
      },
    },
    orderBy: { id: "asc" },
  });

  sendData(res, {
    students: classifications.map((c) => ({
      student: c.studentEnrollment.student,
      program: c.studentEnrollment.program,
      classificationCode: c.classificationCode,
      reasonText: c.explanation?.reasonText ?? null,
    })),
  });
}

/** Backs the "How This Student Counts" panel — spec §19. */
export async function studentExplanation(req: Request, res: Response) {
  const reportingPeriodId = Number(req.params.id);
  const enrollmentId = Number(req.params.enrollmentId);
  await findOwnedPeriod(req.user!.institutionId, reportingPeriodId);
  const accessibleProgramIds = await getAccessibleProgramIds(req.user!);

  const enrollment = await prisma.studentEnrollment.findFirst({
    where: {
      id: enrollmentId,
      student: { institutionId: req.user!.institutionId },
      ...(accessibleProgramIds && { programId: { in: accessibleProgramIds } }),
    },
  });
  if (!enrollment) throw ApiError.notFound("Enrollment not found");

  const classifications = await prisma.studentClassification.findMany({
    where: { reportingPeriodId, studentEnrollmentId: enrollmentId },
    include: { explanation: true },
    orderBy: { metric: "asc" },
  });

  sendData(res, {
    classifications: classifications.map((c) => ({
      metric: c.metric,
      classificationCode: c.classificationCode,
      countsInNumerator: c.explanation?.countsInNumerator ?? false,
      countsInDenominator: c.explanation?.countsInDenominator ?? false,
      reasonText: c.explanation?.reasonText ?? null,
    })),
  });
}
